import fs from "node:fs/promises";

const sources=[
  ["upsc","UPSC","Central Government","https://www.upsc.gov.in/whats-new"],
  ["ssc","Staff Selection Commission","Central Government","https://ssc.gov.in/"],
  ["ibps","IBPS","Banking","https://www.ibps.in/index.php/crp-updates/"],
  ["nta","National Testing Agency","Entrance / Eligibility","https://www.nta.ac.in/NoticeBoardArchive"],
  ["ctet","CTET","Teaching","https://ctet.nic.in/"],
  ["jpsc","Jharkhand Public Service Commission","State Government","https://jpsc.gov.in/"],
  ["jssc","Jharkhand Staff Selection Commission","State Government","https://jssc.jharkhand.gov.in/"],
  ["sbi","State Bank of India","Banking","https://sbi.co.in/web/careers"]
];

const keywords=/notification|advertisement|recruitment|corrigendum|admit.?card|answer.?key|result|vacanc|examination|exam.?notice/i;
const today=new Date().toISOString().slice(0,10);
const decode=s=>s.replace(/&amp;/g,"&").replace(/&#39;/g,"'").replace(/&quot;/g,'"').replace(/&nbsp;/g," ");
const absolute=(href,base)=>{try{return new URL(href,base).href}catch{return null}};
const cleanTitle=s=>decode(s.replace(/<[^>]+>/g," ").replace(/\s+/g," ").trim()).slice(0,180);

const found=[];
for(const [id,organization,category,url] of sources){
  try{
    const res=await fetch(url,{redirect:"follow",headers:{"user-agent":"SarkariPrep-OfficialSourceMonitor/1.0"}});
    if(!res.ok) continue;
    const html=await res.text();
    const re=/<a\b[^>]*href=["']([^"']+)["'][^>]*>([\s\S]*?)<\/a>/gi;
    let m;
    while((m=re.exec(html))){
      const link=absolute(m[1],url); const title=cleanTitle(m[2]);
      if(!link||!title||title.length<8||!keywords.test(title+" "+link)) continue;
      if(link.startsWith("javascript:")||link.includes("#")) continue;
      found.push({id,organization,category,link,title});
    }
  }catch{}
}

const unique=[...new Map(found.map(x=>[x.link,x])).values()]
  .filter(x=>!/login|privacy|accessibility|contact|sitemap/i.test(x.link))
  .slice(0,80);

const body=unique.map((x,i)=>({
 id:"auto-"+Buffer.from(x.link).toString("base64url").slice(0,20)+"-"+i,
 title:x.title,
 organization:x.organization,
 category:x.category,
 stage:"Recruitment",
 status:"Auto-detected official link",
 publishedDate:today,
 lastChecked:today,
 officialUrl:x.link,
 notificationUrl:x.link,
 description:"Automatically detected from an official authority page. Open the original notice and verify the current notification, dates, eligibility and vacancy before acting."
}));

const out='// Generated by scripts/sync-official-notifications.mjs. Do not edit manually.\nimport type {NotificationItem} from "./notifications";\n\nexport const autoNotifications:NotificationItem[]='+JSON.stringify(body,null,2)+';\n';
await fs.writeFile("lib/auto-notifications.ts",out);
console.log("Detected",body.length,"official links");
